function normalizeText(text) {
  return text
    .toLowerCase()
    .replace(/[\s，。！？、,.!?：:；;“”"'《》【】（）()—-]/g, "")
    .replace(/小说|女主|男主|一个|好像|记得|之前|以前|后来|最后|大概|就是/g, "");
}

function getBigrams(text) {
  const normalized = normalizeText(text);
  const values = new Set();
  for (let i = 0; i < normalized.length - 1; i += 1) values.add(normalized.slice(i, i + 2));
  return values;
}

function scoreBook(book, rawQuery, refinements = []) {
  const query = normalizeText(rawQuery);
  const fullText = normalizeText(
    [
      book.title,
      ...book.aliases,
      ...(book.formerNames || []),
      ...book.keywords,
      ...book.characters,
      ...book.genres,
      book.plot,
      ...refinements,
      ...selectedCoverClues,
    ].join(" "),
  );
  let score = 0;
  const evidence = [];

  if (
    normalizeText(book.title) === normalizeText(rawQuery) ||
    [...book.aliases, ...(book.formerNames || [])].some((alias) => normalizeText(alias) === normalizeText(rawQuery))
  ) {
    score += 60;
    evidence.push("书名完全命中");
  } else if (book.title.includes(rawQuery.trim()) || book.aliases.some((alias) => alias.includes(rawQuery.trim()))) {
    score += 38;
    evidence.push("书名相近");
  }

  const keywords = [
    ...book.keywords,
    ...book.characters,
    ...book.aliases,
    ...(book.formerNames || []),
    ...book.genres,
  ];
  const matchedKeywords = [];
  keywords.forEach((keyword) => {
    const normalizedKeyword = normalizeText(keyword);
    if (normalizedKeyword && query.includes(normalizedKeyword) && !matchedKeywords.includes(keyword)) {
      matchedKeywords.push(keyword);
      score += keyword.length > 4 ? 13 : 9;
    }
  });

  matchedKeywords
    .sort((a, b) => b.length - a.length)
    .slice(0, 4)
    .forEach((keyword) => evidence.push(keyword));

  if (query.includes("改名") || query.includes("原名") || query.includes("以前叫")) {
    if (book.formerNames?.length) {
      score += 18;
      evidence.unshift("匹配到曾用名");
    }
  }

  if (selectedCoverClues.length) {
    if (fullText.includes("封面") || book.cover) {
      score += 4;
      selectedCoverClues.slice(0, 2).forEach((clue) => evidence.push(clue));
    }
  }

  const queryBigrams = getBigrams(query);
  const bookBigrams = getBigrams(fullText);
  let overlap = 0;
  queryBigrams.forEach((item) => {
    if (bookBigrams.has(item)) overlap += 1;
  });
  if (queryBigrams.size > 2) {
    score += Math.round((overlap / queryBigrams.size) * 28);
  }

  if (book.isCloud && book.serverScore) {
    score += Math.min(28, Math.round(Math.log2(book.serverScore + 1) * 3));
    evidence.push("云端全文线索命中");
  }

  if (evidence.length < 3) {
    const fallback = [
      book.genres[0],
      book.characters[0],
      book.genres[1] || "故事氛围相近",
    ].filter(Boolean);
    fallback.forEach((item) => {
      if (evidence.length < 3) evidence.push(item);
    });
  }

  const confidence = Math.min(96, Math.max(31, 42 + score));
  return { book, score, confidence, evidence: [...new Set(evidence)].slice(0, 5) };
}

function parseTags(query) {
  const known = [
    "古言",
    "现言",
    "校园",
    "仙侠",
    "穿越",
    "穿书",
    "重生",
    "系统",
    "暗恋",
    "破镜重圆",
    "养成",
    "权谋",
    "改名",
    "虐恋",
    "救赎",
  ];
  const tags = known.filter((tag) => query.includes(tag));
  document.querySelectorAll(".clue.selected").forEach((chip) => {
    if (!tags.includes(chip.dataset.clue)) tags.push(chip.dataset.clue);
  });
  return tags.slice(0, 6);
}

function getClueLines(query) {
  const tags = parseTags(query);
  const clues = [];
  if (tags.length) clues.push(["题材", tags.slice(0, 3).join(" · ")]);
  const character = books.flatMap((book) => book.characters).find((name) => query.includes(name));
  if (character) clues.push(["人物", character]);
  const modeClues = {
    plot: "故事桥段与人物关系",
    title: "书名、字数与曾用名",
    cover: selectedCoverClues.join(" · ") || "封面视觉特征",
    quote: "台词与语言细节",
  };
  clues.push(["重点", modeClues[activeMode]]);
  if (selectedCoverClues.length) clues.push(["封面", selectedCoverClues.join(" · ")]);
  clues.push(["检索范围", cloudConnected ? "4,679 本云端书目 · 别名库 · 社区线索" : "本地示例 · 别名库 · 社区线索"]);
  return clues.slice(0, 5);
}

