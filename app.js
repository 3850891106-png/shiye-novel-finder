async function supabaseRequest(path, options = {}) {
  if (!cloudEnabled) throw new Error("Supabase is not configured");
  const url = `${cloudConfig.supabaseUrl.replace(/\/$/, "")}/rest/v1/${path}`;
  const response = await fetch(url, {
    method: options.method || "GET",
    headers: {
      apikey: cloudConfig.supabaseAnonKey,
      Authorization: `Bearer ${cloudConfig.supabaseAnonKey}`,
      "Content-Type": "application/json",
      ...(options.headers || {}),
    },
    body: options.body == null ? undefined : JSON.stringify(options.body),
  });
  if (!response.ok) {
    const detail = await response.text();
    throw new Error(`Supabase ${response.status}: ${detail.slice(0, 220)}`);
  }
  const text = await response.text();
  return text ? JSON.parse(text) : null;
}

function normalizeList(value) {
  if (Array.isArray(value)) return value.filter(Boolean).map(String);
  if (typeof value !== "string" || !value.trim()) return [];
  return value
    .split(/[|、]/)
    .map((item) => item.trim())
    .filter(Boolean);
}

