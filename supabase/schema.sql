create extension if not exists pg_trgm;

create table if not exists public.novels (
  id bigint generated by default as identity primary key,
  source_seq bigint not null unique,
  title text not null,
  author text not null default '',
  category text not null default '',
  status text not null default '',
  source_updated_at timestamptz,
  latest_chapter text not null default '',
  character_candidates text not null default '',
  characters text[] not null default '{}',
  fetched_chapter_count integer not null default 0,
  chapter_titles text not null default '',
  synopsis text not null default '',
  travel_evidence text not null default '',
  source_url text not null default '',
  source_name text not null default '香书小说公开页面',
  aliases text[] not null default '{}',
  search_text text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists novels_title_trgm_idx
  on public.novels using gin (lower(title) gin_trgm_ops);

create index if not exists novels_search_text_trgm_idx
  on public.novels using gin (lower(search_text) gin_trgm_ops);

create index if not exists novels_category_idx
  on public.novels (category);

create index if not exists novels_status_idx
  on public.novels (status);

create table if not exists public.novel_requests (
  id uuid primary key default gen_random_uuid(),
  clue text not null check (char_length(clue) between 10 and 600),
  genre text not null default '' check (char_length(genre) <= 30),
  read_period text not null default '' check (char_length(read_period) <= 30),
  nickname text not null default '' check (char_length(nickname) <= 30),
  status text not null default 'published' check (status in ('published', 'hidden')),
  created_at timestamptz not null default now()
);

create index if not exists novel_requests_created_at_idx
  on public.novel_requests (created_at desc);

alter table public.novels enable row level security;
alter table public.novel_requests enable row level security;

drop policy if exists "Public novels are readable" on public.novels;
create policy "Public novels are readable"
  on public.novels for select
  to anon, authenticated
  using (true);

drop policy if exists "Published requests are readable" on public.novel_requests;
create policy "Published requests are readable"
  on public.novel_requests for select
  to anon, authenticated
  using (status = 'published');

drop policy if exists "Anyone can submit a valid request" on public.novel_requests;
create policy "Anyone can submit a valid request"
  on public.novel_requests for insert
  to anon, authenticated
  with check (
    status = 'published'
    and char_length(clue) between 10 and 600
    and char_length(genre) <= 30
    and char_length(read_period) <= 30
    and char_length(nickname) <= 30
  );

revoke update, delete on public.novel_requests from anon, authenticated;

create or replace function public.novel_stats()
returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
  select jsonb_build_object(
    'novel_count', (select count(*) from public.novels),
    'alias_count', (select coalesce(sum(cardinality(aliases)), 0) from public.novels),
    'request_count', (
      select count(*)
      from public.novel_requests
      where status = 'published'
    )
  );
$$;

create or replace function public.search_novels(
  search_query text default '',
  search_terms text[] default '{}',
  max_rows integer default 20
)
returns table (
  id bigint,
  source_seq bigint,
  title text,
  author text,
  category text,
  status text,
  source_updated_at timestamptz,
  latest_chapter text,
  characters text[],
  synopsis text,
  travel_evidence text,
  source_url text,
  aliases text[],
  score double precision
)
language sql
stable
security invoker
set search_path = public
as $$
  with params as (
    select
      trim(coalesce(search_query, '')) as raw_query,
      lower(regexp_replace(trim(coalesce(search_query, '')), '\s+', '', 'g')) as compact_query
  ),
  terms as (
    select distinct lower(trim(term)) as term
    from unnest(coalesce(search_terms, '{}')) as term
    where char_length(trim(term)) >= 2
    limit 20
  ),
  scored as (
    select
      n.*,
      (
        case
          when lower(n.title) = p.compact_query then 120
          when p.compact_query <> '' and strpos(lower(n.title), p.compact_query) > 0 then 70
          else 0
        end
        + case
            when p.compact_query <> '' then similarity(lower(n.title), p.compact_query) * 45
            else 0
          end
        + coalesce(
            (
              select sum(least(char_length(t.term) * 3.0, 18))
              from terms t
              where strpos(lower(n.search_text), t.term) > 0
            ),
            0
          )
      )::double precision as rank_score
    from public.novels n
    cross join params p
  )
  select
    s.id,
    s.source_seq,
    s.title,
    s.author,
    s.category,
    s.status,
    s.source_updated_at,
    s.latest_chapter,
    s.characters,
    s.synopsis,
    s.travel_evidence,
    s.source_url,
    s.aliases,
    s.rank_score
  from scored s
  where s.rank_score >= 1
  order by s.rank_score desc, s.source_seq asc
  limit least(greatest(coalesce(max_rows, 20), 1), 50);
$$;

grant execute on function public.novel_stats() to anon, authenticated;
grant execute on function public.search_novels(text, text[], integer) to anon, authenticated;

